"""Generate offline firmware catalogs and a small Unicode font subset.

Run python3 scripts/generate_localization.py (no packages/network required).
For newly used codepoints, pass --font-source /path/to/unifont-18.0.01.hex.gz.
Font glyphs are licensed under SIL OFL 1.1; see assets/fonts/README.md.
"""
import argparse
import gzip
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def generate(font_source=None, check=False):
    catalog = json.loads((ROOT / 'locales/translations.json').read_text())
    languages, strings = catalog['languages'], catalog['strings']
    count = len(languages)
    assert count == 8 and languages[0]['code'] == 'pt-BR'
    for key, values in strings.items():
        assert len(values) == count and all(values), key
        formats = [re.findall(r'%(?:lu|[dsu])|\{\w+\}', text) for text in values]
        assert all(sorted(f) == sorted(formats[0]) for f in formats), key
    quote = lambda s: json.dumps(s, ensure_ascii=False)
    ids = ['TXT_' + key.upper() for key in strings]
    header = ['// Generated by scripts/generate_localization.py. Edit locales/translations.json.',
              '#pragma once', '#include <stdint.h>',
              f'constexpr uint8_t LANGUAGE_COUNT = {count};',
              'enum TextId { ' + ', '.join(ids) + ', TXT_COUNT };',
              'constexpr const char* LANGUAGE_CODES[] = {' + ', '.join(quote(l['code']) for l in languages) + '};',
              'constexpr const char* LANGUAGE_NAMES[] = {' + ', '.join(quote(l['name']) for l in languages) + '};',
              'uint8_t activeLanguage = 0;',
              'constexpr const char* UI_TEXT[LANGUAGE_COUNT][TXT_COUNT] = {']
    for lang in range(count):
        header += ['  { // ' + languages[lang]['code']]
        header += ['    ' + quote(values[lang]) + ',' for values in strings.values()]
        header += ['  },']
    header += ['};', 'inline const char* tr(TextId id) {',
               '  return UI_TEXT[activeLanguage < LANGUAGE_COUNT ? activeLanguage : 0][id];', '}',
               'constexpr const char* LANGUAGE_WEB_JSON[] = {']
    for lang in range(count):
        data = dict(language=lang, code=languages[lang]['code'], languages=languages,
                    strings={key: values[lang] for key, values in strings.items()})
        header += ['  ' + quote(json.dumps(data, ensure_ascii=False, separators=(',', ':'))) + ',']
    header += ['};', '']
    needed = set(range(32, 127)) | {ord(c) for v in strings.values() for s in v for c in s}
    needed |= {ord(c) for lang in languages for c in lang['name']}
    source = Path(font_source) if font_source else ROOT / 'assets/fonts/passvault.hex'
    raw = gzip.open(source, 'rt').read() if source.suffix == '.gz' else source.read_text()
    glyphs = {int(line.split(':')[0], 16): line.split(':')[1] for line in raw.splitlines() if ':' in line}
    missing = needed - glyphs.keys()
    if missing:
        raise ValueError('Missing glyphs: ' + ', '.join(f'U+{c:04X}' for c in sorted(missing)))
    subset = ''.join(f'{c:04X}:{glyphs[c]}\n' for c in sorted(needed))
    font = ['// PassVault UI subset of GNU Unifont 18.0.01 (SIL OFL 1.1).',
            '// Generated by scripts/generate_localization.py. See assets/fonts/README.md.',
            '#pragma once', '#include <stdint.h>',
            'struct UiGlyph { uint16_t codepoint; uint8_t width; uint8_t bits[32]; };',
            'constexpr UiGlyph UI_GLYPHS[] = {']
    for code in sorted(needed):
        data = bytes.fromhex(glyphs[code])
        assert len(data) in (16, 32)
        width = len(data) // 2
        font += ['  {' + f'{code}, {width}, ' + '{' + ','.join(f'0x{b:02x}' for b in data.ljust(32, b'\0')) + '}},']
    font += ['};', 'constexpr unsigned UI_GLYPH_COUNT = sizeof(UI_GLYPHS) / sizeof(UI_GLYPHS[0]);', '']
    outputs = {'include/localization.h': '\n'.join(header), 'include/unicode_font.h': '\n'.join(font),
               'assets/fonts/passvault.hex': subset}
    for name, value in outputs.items():
        target = ROOT / name
        if check:
            assert target.read_text() == value, 'Regenerate ' + name
        else:
            target.write_text(value)
    return catalog


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--font-source')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generate(args.font_source, args.check)
